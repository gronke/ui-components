//! Generates `bootstrap-tui.gen.css` by filtering the real compiled
//! Bootstrap (vendored by build.rs) through the dialect: only rules whose
//! selectors parse and whose declarations name supported properties
//! survive, values staying in Bootstrap's own units — the engine's cell
//! conversion does the math at computed-value time.
//!
//! ```sh
//! cargo run -p uic_css --bin gen-tui-css
//! ```
//!
//! The output is committed; rerun on Bootstrap version bumps and review the
//! diff.

use std::fmt::Write as _;

use cssparser::ToCss as _;
use selectors::parser::{Component, Selector};
use uic_css::{parse_stylesheet, TuiSelectors};

const OUTPUT: &str = "crates/uic_tui/css/bootstrap-tui.gen.css";

fn main() {
    let source = std::fs::read_to_string(env!("UIC_CSS_BOOTSTRAP")).expect("vendored bootstrap");
    let (sheet, report) = parse_stylesheet(&source);

    // The utility filter: the terminal adopts Bootstrap's utility layer, not
    // its element reboot — bare-element base rules stay ua.css territory.
    // A selector survives when its subject compound carries a class or an
    // attribute (or is :root, the custom-property carrier).
    let mut kept_rules = 0usize;
    let mut kept_text = String::new();
    for rule in &sheet.rules {
        let selectors: Vec<String> = rule
            .selectors
            .slice()
            .iter()
            .filter(|selector| keep_selector(selector))
            .map(|selector| selector.to_css_string())
            .collect();
        if selectors.is_empty() {
            continue;
        }
        kept_rules += 1;
        let _ = writeln!(kept_text, "{} {{", selectors.join(", "));
        for declaration in &rule.declarations {
            let bang = if declaration.important {
                " !important"
            } else {
                ""
            };
            let _ = writeln!(
                kept_text,
                "    {}: {}{};",
                declaration.name, declaration.value, bang
            );
        }
        let _ = writeln!(kept_text, "}}");
    }

    let mut out = String::new();
    let _ = writeln!(
        out,
        "/* Generated by gen-tui-css from the vendored bootstrap/dist/css/bootstrap.css."
    );
    let _ = writeln!(
        out,
        "   The dialect kept {kept_rules} utility rules of {} parsed; {} declarations,",
        sheet.rules.len(),
        report.declarations.len(),
    );
    let _ = writeln!(
        out,
        "   {} selectors and {} at-rules dropped per the degradation contract;",
        report.selectors.len(),
        report.at_rules.len()
    );
    let _ = writeln!(
        out,
        "   bare-element base rules stay ua.css territory. Do not edit — rerun the generator. */"
    );
    out.push_str(&kept_text);

    let repo_root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("repo root");
    let path = repo_root.join(OUTPUT);
    std::fs::create_dir_all(path.parent().expect("css dir")).expect("create css dir");
    std::fs::write(&path, &out).expect("write generated sheet");
    println!(
        "wrote {} ({kept_rules} rules, {} bytes)",
        path.display(),
        out.len()
    );
}

fn keep_selector(selector: &Selector<TuiSelectors>) -> bool {
    // `iter()` walks the subject (rightmost) compound up to the first
    // combinator — exactly the utility test's scope.
    selector.iter().any(|component| {
        matches!(
            component,
            Component::Class(_)
                | Component::ID(_)
                | Component::AttributeInNoNamespaceExists { .. }
                | Component::AttributeInNoNamespace { .. }
                | Component::AttributeOther(_)
                | Component::Root
        )
    })
}
